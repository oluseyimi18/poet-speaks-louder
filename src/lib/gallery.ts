/**
 * Camera burst shots land next to each other once sorted by filename (same
 * pose, a fraction of a second apart) — scrolling the gallery would show the
 * same moment three times in a row. This splits the sorted list into
 * `chunks` contiguous slices spanning the whole shoot and round-robins across
 * them, so photos taken seconds apart end up `chunks` slots apart instead of
 * adjacent. Deterministic, so the order is stable across builds.
 */
function declusterBursts<T>(items: T[], chunks = 6): T[] {
  if (items.length <= chunks) return items;
  const size = Math.ceil(items.length / chunks);
  const groups: T[][] = [];
  for (let i = 0; i < items.length; i += size) {
    groups.push(items.slice(i, i + size));
  }
  const result: T[] = [];
  const maxLen = Math.max(...groups.map((g) => g.length));
  for (let p = 0; p < maxLen; p++) {
    for (const g of groups) {
      if (g[p] !== undefined) result.push(g[p]);
    }
  }
  return result;
}

/**
 * Lists photos in public/photos/gallery/<slug>/, generated by
 * scripts/build-gallery-photos.mjs. Reads each photo's real dimensions (fast —
 * these are already small, pre-resized files) so the gallery can lay them out
 * as a true masonry grid instead of forcing a fixed aspect ratio. A category
 * with no photos yet is still returned (empty photos array), so the gallery
 * can show a "developing" placeholder instead of silently disappearing.
 */
export async function getGalleryCategories(): Promise<GalleryCategory[]> {
  return Promise.all(
    CATEGORY_META.map(async (meta) => {
      const dir = path.join(process.cwd(), "public", "photos", "gallery", meta.slug);
      let files: string[] = [];
      try {
        files = fs
          .readdirSync(dir)
          .filter((f) => IMAGE_RE.test(f))
          .sort((a, b) => a.localeCompare(b));
      } catch {
        files = [];
      }

      const ordered = declusterBursts(files);
      const photos = await Promise.all(
        ordered.map(async (f, i): Promise<GalleryPhoto> => {
          const metadata = await sharp(path.join(dir, f)).metadata();
          return {
            src: `/photos/gallery/${meta.slug}/${f}`,
            alt: `${meta.blurb} — photo ${i + 1}`,
            width: metadata.width ?? 1600,
            height: metadata.height ?? 1200,
          };
        }),
      );

      return { ...meta, photos };
    }),
  );
}
